export const dict: Record<Lang, Record<StrKey, string>> = { en, zh };

export const LangContext = createContext<Lang>('en');

export function useLang(): Lang {
  return useContext(LangContext);
}

export function useT(): (k: StrKey) => string {
  const lang = useContext(LangContext);
  return (k) => dict[lang][k] ?? en[k];
}

/** Fill `{slot}` placeholders in a string — the fx_* reasons carry a
 *  mid-sentence value whose position differs between the languages (English
 *  ends 'Pick a market for {word}' with it; Chinese puts it mid-sentence).
 *  Unknown slots stay verbatim. */
export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
